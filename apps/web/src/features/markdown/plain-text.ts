/**
 * Markdown 源文 → 紧凑单行纯文本（原生 <option> 标签、错题摘要等**纯文本
 * 语境**共用单源；富文本渲染恒走 RichMarkdown，不经过这里）。
 *
 * 保守清洗原则：只剥确定的装饰语法，正文照抄——宁可露出原文也不改写
 * 字面内容（货币 $、下划线变量名、乘号 * 等都不允许被「顺手」吃掉）：
 * - 图片/链接 → 链接文字（URL 模式允许成对括号，不截断 wiki 风格地址）；
 * - 公式：显示级 `$$…$$` 剥定界符保留内容；行内 `$…$` 仅当内容不含空白
 *   且不含 CJK 才剥（避开「利润为 $5，成本 $3」之类货币文本被误当定界）；
 * - 成对的 **、__、~~、` 装饰定界符剥除；单个 * 或 _ 视为字面字符保留；
 * - 空白折叠只折 ASCII（\s 会吞全角空格 U+3000，破坏「（　）」空框——
 *   与 wrong-questions-ui 摘要的既有教训同源，收敛到本处后不再各写一份）。
 */
export function plainInlineMdOf(text: string): string {
  return text
    .replace(/!\[([^\]]*)\]\((?:[^()\s]|\([^()]*\))*\)/g, "$1")
    .replace(/\[([^\]]+)\]\((?:[^()\s]|\([^()]*\))*\)/g, "$1")
    .replace(/\$\$([\s\S]+?)\$\$/g, "$1")
    .replace(/\$([^$]+)\$/g, (whole, content: string) =>
      content.length > 0 && !/\s/.test(content) && !/[一-鿿]/.test(content)
        ? content
        : whole,
    )
    .replace(/\*\*([^*]+?)\*\*/g, "$1")
    .replace(/__([^_]+?)__/g, "$1")
    .replace(/~~([^~]+?)~~/g, "$1")
    .replace(/`([^`]+?)`/g, "$1")
    .replace(/[ \t\r\n]+/g, " ")
    .trim();
}
